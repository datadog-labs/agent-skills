def _policy_name_line(content: str) -> "re.Match | None":
    """The aws_iam_policy name line, e.g. name = "<role>-policy-${count.index + 1}"."""
    return re.search(r'name\s*=\s*"(?P<base>[^"]+)-\$\{count\.index \+ 1\}"', content)


def _renamed_policy_base(base: str, existing: "list[str]") -> "str | None":
    """A verified-free replacement for the policy-name base.

    '<role>-policy' keeps its shape — the MMDD suffix goes into the role part
    ('<role>-1119-policy'), matching what precheck's collision resolution would
    generate. Legacy bases (e.g. DatadogAWSIntegrationPolicy) just get the
    suffix appended.
    """
    date = _date_suffix()
    stem = base[: -len("-policy")] if base.endswith("-policy") else base
    tail = "-policy" if base.endswith("-policy") else ""
    candidates = [f"{stem}-{date}{tail}"] + [f"{stem}-{date}-{i}{tail}" for i in range(2, 10)]
    return next((c for c in candidates if _policies_collide(c, existing) is False), None)


def cmd_fix(args: argparse.Namespace) -> None:
    """Rename the integration's policy set in main.tf past a collision.

    Run after `terraform apply` fails with 409 EntityAlreadyExists on one of
    the integration's policy names: probes IAM for the names main.tf would
    create, and when they are taken rewrites them with a verified-free MMDD
    date suffix. Policies the failed apply did manage to create are already in
    Terraform state; the rename forces their replacement, so the next plan
    cleans them up — no orphans and no hand-editing.
    """
    dir_path = pathlib.Path(args.dir)
    tf_path = dir_path / "main.tf"
    if not tf_path.is_file():
        _die(f"{tf_path} not found")

    content = tf_path.read_text()
    m = _policy_name_line(content)
    if not m:
        _die("no policy-name template with ${count.index + 1} found in main.tf — nothing to fix")

    base = m.group("base")  # e.g. datadog-aws-integration-role-policy

    profile = args.aws_profile or os.environ.get("AWS_PROFILE", "") or None
    print(f"Probing AWS IAM for '{base}-*' policies ...", file=sys.stderr)
    local_policies = _list_local_policies(profile)
    if local_policies is None:
        _die("aws iam list-policies failed — check credentials and re-run")

    colliding = sorted(n for n in local_policies if n.startswith(base + "-"))
    if not colliding:
        print(f"✓ no '{base}-*' policies exist in IAM — nothing to fix (the 409 was probably on another resource; re-run precheck)")
        return

    print(f"✗ colliding with {len(colliding)} existing polic{'y' if len(colliding) == 1 else 'ies'}: {', '.join(colliding)}", file=sys.stderr)

    new_base = _renamed_policy_base(base, local_policies)
    if new_base is None:
        _die(f"no free policy-name suffix found for base '{base}' — pass a distinct --role-name to gen and regenerate")

    tf_path.write_text(content.replace(f'"{base}-${{count.index + 1}}"', f'"{new_base}-${{count.index + 1}}"'))
    print(f"✓ rewrote policy names in {tf_path}: '{base}-${{count.index + 1}}' -> '{new_base}-${{count.index + 1}}'")
    print("  policies created by the failed apply are in Terraform state; the next plan replaces them")
    print("next: terraform plan -out=tfplan   # show the plan, get confirmation, then apply tfplan")


