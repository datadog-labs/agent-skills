#!/usr/bin/env python3
"""tf.py — Datadog AWS integration Terraform helper.

Subcommands
-----------
  gen       Emit a standalone main.tf for the integration.
  precheck  Query local state, Datadog API, and AWS IAM before first apply.
            Default-name IAM collisions (role or its -policy-* names) are
            auto-resolved with a MMDD date suffix, e.g. role-1119.
  fix       After an apply 409 (EntityAlreadyExists) on the integration's policy
            names, rewrite them in main.tf with a verified-free MMDD suffix.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import pathlib
import re
import shlex
import subprocess
import sys

# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

def _die(msg: str, code: int = 1) -> None:
    print(f"✗ {msg}", file=sys.stderr)
    sys.exit(code)


def _validate_account(account: str, flag: str = "--account") -> None:
    if not re.fullmatch(r"\d{12}", account):
        _die(f"{flag} must be a 12-digit id")


def _validate_role_name(role_name: str) -> None:
    # IAM role-name rules; the policies are named after the role, so this also keeps them valid.
    if not re.fullmatch(r"[\w+=,.@-]{1,64}", role_name):
        _die("--role-name must be 1-64 characters from letters and digits and +=,.@_-")


DEFAULT_ROLE_NAME = "datadog-aws-integration-role"


def _policy_prefix(role_name: str) -> str:
    """The policy-name prefix the template derives from a role name.

    datadog-aws-integration-role-1119 -> datadog-aws-integration-role-1119-policy
    Policies carry the role's distinguishing suffix, so a role name that is
    free of collisions implies a policy-name range that is free too.
    """
    return f"{role_name}-policy"


def _date_suffix() -> str:
    """MMDD, e.g. 1119 for Nov 19 — the collision-recovery name component."""
    return datetime.datetime.now().strftime("%m%d")


