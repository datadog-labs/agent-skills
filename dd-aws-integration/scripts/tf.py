def _run(cmd: list, **kwargs) -> "subprocess.CompletedProcess":
    return subprocess.run(cmd, capture_output=True, text=True, **kwargs)


# IAM resources the integration template creates (tf.py gen and references/terraform.md).
_INTEGRATION_IAM = {
    ("aws_iam_role", "datadog_aws_integration"),
    ("aws_iam_policy", "datadog_aws_integration"),
    ("aws_iam_role_policy_attachment", "datadog_aws_integration"),
    ("aws_iam_role_policy_attachment", "datadog_aws_integration_security_audit"),
}


def _has_tf_files(dir_path: pathlib.Path) -> bool:
    return any(dir_path.glob("*.tf")) or any(dir_path.glob("*.tf.json"))


def _default_precheck_dir() -> pathlib.Path:
    """The standalone project tf.py gen writes, else the current project, else the gen default."""
    standalone = pathlib.Path("./dd-aws-integration")
    if _has_tf_files(standalone):
        return standalone
    if _has_tf_files(pathlib.Path(".")):
        return pathlib.Path(".")
    return standalone


def _state_resources(show: dict) -> list[dict]:
    """Flatten `terraform show -json` output into its resources, child modules included."""
    resources = []
    modules = [show.get("values", {}).get("root_module", {})]
    while modules:
        module = modules.pop()
        resources.extend(module.get("resources", []))
        modules.extend(module.get("child_modules", []))
    return resources


def _summarize_state(show: dict, account: str) -> dict:
    """What a project's state says about this integration, for this account."""
    resources = [r for r in _state_resources(show) if r.get("mode") == "managed"]
    # A registration counts only when it is for THIS account: a project left over from another
    # account's install says nothing about this one.
    registered_accounts = {
        str((r.get("values") or {}).get("aws_account_id") or "")
        for r in resources if r.get("type") == "datadog_integration_aws_account"
    } - {""}
    has_registration = account in registered_accounts
    has_integration_iam = any((r.get("type"), r.get("name")) in _INTEGRATION_IAM for r in resources)
    return {
        "configured": True,
        "has_state": bool(resources),
        "has_registration": has_registration,
        "other_accounts": sorted(registered_accounts - {account}),
        "has_integration_resources": has_registration or has_integration_iam,
        "addresses": [r.get("address", "") for r in resources],
    }


def _check_local_state(dir_path: pathlib.Path, account: str, profile: str | None) -> dict:
    if not _has_tf_files(dir_path):
        return {
            "configured": False, "has_state": False, "has_registration": False, "other_accounts": [],
            "has_integration_resources": False, "addresses": [],
        }

    # The backend may need the verified AWS profile, same as any other Terraform command.
    env = {**os.environ, "TF_IN_AUTOMATION": "1"}
    if profile:
        env["AWS_PROFILE"] = profile

    # init quietly
    init = _run(["terraform", "init", "-input=false"], cwd=str(dir_path), env=env)
    if init.returncode != 0:
        # init failure is a hard failure — we can't proceed
        _die(f"terraform init failed:\n{init.stderr.strip()}")

    # `show -json` carries each resource's attributes (so the registration's aws_account_id), and
    # prints a document with no `values` when there is no state yet.
    show = _run(["terraform", "show", "-json"], cwd=str(dir_path), env=env)
    if show.returncode != 0:
        _die(f"terraform show failed (possible backend/auth problem):\n{show.stderr.strip()}")
    try:
        state = json.loads(show.stdout or "{}")
    except json.JSONDecodeError as exc:
        _die(f"terraform show -json returned invalid JSON: {exc}")
    return _summarize_state(state, account)


def _check_datadog_api(site: str, account: str) -> dict:
    api_key = os.environ.get("DD_API_KEY", "")
    app_key = os.environ.get("DD_APP_KEY", "")

    url = f"https://api.{site}/api/v2/integration/aws/accounts"

    # Keys via stdin (-H @-) — never in argv, so they never land in ps / shell history.
    # Matches the pattern in scripts/dd-env.sh and scripts/verify.py.
    result = _run(
        ["curl", "-sS", "--max-time", "30", "-w", "\n%{http_code}", "-H", "@-", url],
        input=f"DD-API-KEY: {api_key}\nDD-APPLICATION-KEY: {app_key}\n",
    )

    if result.returncode != 0:
        _die(f"curl failed: {result.stderr.strip()}")

    body, _, status_code = result.stdout.rpartition("\n")
    status_code = status_code.strip() or "0"

    if status_code != "200":
        print(f"✗ Datadog API returned HTTP {status_code}", file=sys.stderr)
        if body:
            print(f"  Response: {body[:200]}", file=sys.stderr)
        sys.exit(1)

    try:
        data = json.loads(body)
    except json.JSONDecodeError as exc:
        _die(f"Datadog API returned invalid JSON: {exc}")

    entries = data.get("data", [])
    match = None
    for entry in entries:
        attrs = entry.get("attributes", {})
        if attrs.get("aws_account_id") == account:
            match = entry
            break

    if not match:
        return {"registered": False, "config_id": None, "role_name": None}

    config_id = match.get("id")
    auth_config = match.get("attributes", {}).get("auth_config", {})
    role_name = None
    # auth_config may have various shapes; look for role_name anywhere one level deep
    for _k, v in auth_config.items():
        if isinstance(v, dict) and "role_name" in v:
            role_name = v["role_name"]
            break

    return {"registered": True, "config_id": config_id, "role_name": role_name}


def _check_aws_role(role_name: str, profile: str | None) -> dict:
    cmd = ["aws", "iam", "get-role", "--role-name", role_name]
    if profile:
        cmd += ["--profile", profile]

    result = _run(cmd)
    if result.returncode == 0:
        return {"name": role_name, "exists": True, "error": None}

    stderr = result.stderr.strip()
    if "NoSuchEntity" in stderr or "not found" in stderr.lower():
        return {"name": role_name, "exists": False, "error": None}

    # Other errors (AccessDenied, etc.) — informational, don't fail
    return {"name": role_name, "exists": None, "error": stderr[:300]}


def _list_local_policies(profile: str | None) -> "list[str] | None":
    """All customer-managed policy names in the account, or None on error."""
    names: list[str] = []
    marker = None
    while True:
        cmd = ["aws", "iam", "list-policies", "--scope", "Local", "--output", "json"]
        if marker:
            cmd += ["--marker", marker]
        if profile:
            cmd += ["--profile", profile]
        result = _run(cmd)
        if result.returncode != 0:
            return None
        data = json.loads(result.stdout)
        names += [p["PolicyName"] for p in data.get("Policies", [])]
        if data.get("IsTruncated"):
            marker = data.get("Marker")
        else:
            return names


def _policies_collide(prefix: str, existing: "list[str] | None") -> "bool | None":
    """True if any local policy occupies the prefix's name range.

    None means the probe failed (treated as no collision, but reported).
    """
    if existing is None:
        return None
    return any(n.startswith(prefix + "-") for n in existing)


def _find_free_role_name(existing_policies: "list[str] | None", profile: str | None) -> "str | None":
    """First verified-free date-suffixed role name, or None.

    A candidate is free when the IAM role is absent AND no local policy occupies
    the candidate's policy-name range. Unverifiable probes (None) disqualify.
    """
    if existing_policies is None:
        return None
    date = _date_suffix()
    candidates = [f"{DEFAULT_ROLE_NAME}-{date}"] + [
        f"{DEFAULT_ROLE_NAME}-{date}-{i}" for i in range(2, 10)
    ]
    for cand in candidates:
        probe = _check_aws_role(cand, profile)
        if probe.get("exists") is not False:
            continue
        if _policies_collide(_policy_prefix(cand), existing_policies) is not False:
            continue
        return cand
    return None


def _decide_action(account: str, local: dict, dd: dict, aws_role: dict,
                   policy_collides: bool = False) -> tuple[str, str]:
    registered = dd["registered"]
    has_registration = local["has_registration"]

    if registered and has_registration:
        return "update_in_place", "Integration exists in both Datadog and local Terraform state."

    if registered:
        tile = f"{os.environ.get('APP_BASE', 'https://app.datadoghq.com')}/integrations/amazon-web-services"
        return "import_needed", (
            f"Integration already registered in Datadog (config_id={dd['config_id']}); "
            f"nothing to do — the account is connected. Check its status on {tile}."
        )

    if has_registration:
        return "partial_rollback", (
            "Local Terraform state registers this account but Datadog does not; "
            "the plan re-creates the registration."
        )

    if local["other_accounts"]:
        return "different_account", (
            f"This Terraform project manages the integration for account {', '.join(local['other_accounts'])}, "
            f"not {account}; generate this account's configuration in a separate --dir."
        )

    # Only this integration's own resources count; unrelated resources in a shared project
    # mean nothing about it, and are never a reason to destroy anything.
    if local["has_integration_resources"]:
        return "partial_rollback", (
            "Local Terraform state has resources from this integration but the account is not registered "
            "in Datadog; the plan re-creates the registration."
        )

    # clean_install candidate — but only if the role probe actually answered.
    if aws_role.get("exists") is None:
        return "aws_role_unknown", (
            f"Could not check whether IAM role '{aws_role['name']}' exists: {aws_role.get('error')}. "
            "Fix the AWS credentials (re-run aws-setup.sh) and re-run precheck."
        )

    if aws_role.get("exists") is True or policy_collides:
        taken = []
        if aws_role.get("exists") is True:
            taken.append(f"IAM role '{aws_role['name']}'")
        if policy_collides:
            taken.append(f"policies '{_policy_prefix(aws_role['name'])}-*'")
        return "aws_role_collision", (
            "; ".join(taken)
            + " already exist in AWS but integration is not registered; choose a different "
            "--role-name (the policies are named after it) or import the existing role."
        )

    return "clean_install", "No prior integration found; ready for a fresh terraform apply."


def cmd_precheck(args: argparse.Namespace) -> None:
    _validate_account(args.account)

    # Read required env vars
    site = os.environ.get("DD_SITE", "")
    api_key = os.environ.get("DD_API_KEY", "")
    app_key = os.environ.get("DD_APP_KEY", "")
    missing = [n for n, v in [("DD_SITE", site), ("DD_API_KEY", api_key), ("DD_APP_KEY", app_key)] if not v]
    if missing:
        _die(f"Missing required environment variable(s): {', '.join(missing)}")

    dir_path = pathlib.Path(args.dir) if args.dir else _default_precheck_dir()
    profile = args.aws_profile or os.environ.get("AWS_PROFILE", "") or None

    print(f"Checking local Terraform state in {dir_path} ...", file=sys.stderr)
    local = _check_local_state(dir_path, args.account, profile)

    print(f"Querying Datadog API for account {args.account} ...", file=sys.stderr)
    dd = _check_datadog_api(site, args.account)

    role_name = args.role_name or DEFAULT_ROLE_NAME
    explicit_role_name = args.role_name is not None
    policy_prefix = _policy_prefix(role_name)

    print(f"Probing AWS IAM role '{role_name}' and '{policy_prefix}-*' policies ...", file=sys.stderr)
    aws_role = _check_aws_role(role_name, profile)
    local_policies = _list_local_policies(profile)
    policy_collides = _policies_collide(policy_prefix, local_policies)
    colliding_names = sorted(n for n in (local_policies or []) if n.startswith(policy_prefix + "-"))

    action, message = _decide_action(args.account, local, dd, aws_role, bool(policy_collides))

    # Default-name collisions are resolved by the script, never by the agent: derive a
    # MMDD date-suffixed role name, verify the role AND its policy-name range are free.
    resolved_role_name = None
    if action == "aws_role_collision" and not explicit_role_name:
        resolved_role_name = _find_free_role_name(local_policies, profile)
        if resolved_role_name:
            action = "name_collision_resolved"
            taken = []
            if aws_role.get("exists") is True:
                taken.append(f"role '{aws_role['name']}'")
            if policy_collides:
                taken.append(f"policies '{policy_prefix}-*'")
            message = (
                f"Default IAM names are taken ({', '.join(taken)} - leftovers from a prior attempt); "
                f"verified free replacement role name '{resolved_role_name}' "
                f"(policies '{_policy_prefix(resolved_role_name)}-N'). "
                f"Run gen with --role-name {resolved_role_name}."
            )
        else:
            message += " No free date-suffixed name could be verified; pass an explicit --role-name."

    result = {
        "site": site,
        "account": args.account,
        "dir": str(dir_path),
        "local": local,
        "datadog": dd,
        "aws_role": aws_role,
        "aws_policies": {
            "prefix": policy_prefix,
            "collides": policy_collides,
            "existing": colliding_names,
            "error": None if local_policies is not None else "aws iam list-policies failed",
        },
        "resolved_role_name": resolved_role_name,
        "action": action,
        "message": message,
    }

    print(json.dumps(result))

    # Human-readable summary to stderr
    print("", file=sys.stderr)
    print(f"  dir     : {dir_path}", file=sys.stderr)
    print(f"  local   : configured={local['configured']} has_state={local['has_state']} has_registration={local['has_registration']} other_accounts={local['other_accounts']}", file=sys.stderr)
    print(f"  datadog : registered={dd['registered']} config_id={dd['config_id']}", file=sys.stderr)
    print(f"  aws_role: exists={aws_role['exists']} name={aws_role['name']}" + (f" error={aws_role['error']}" if aws_role["error"] else ""), file=sys.stderr)
    print(f"  policies: collides={policy_collides} prefix={policy_prefix}-*", file=sys.stderr)
    if resolved_role_name:
        print(f"  resolved: role_name={resolved_role_name}", file=sys.stderr)
    print(f"  action  : {action}", file=sys.stderr)
    print(f"  message : {message}", file=sys.stderr)


