def _parse_regions(regions: str) -> list[str]:
    """Split --regions on commas, tolerating spaces; each entry must look like an AWS region."""
    parsed = [r.strip() for r in regions.split(",") if r.strip()]
    for region in parsed:
        if not re.fullmatch(r"[a-z]{2}(-[a-z]+)+-\d+", region):
            _die(f"--regions: {region!r} is not an AWS region name")
    return parsed


def _build_regions_block(regions: list[str]) -> str:
    """Return the aws_regions inner line."""
    if not regions:
        return "    include_all = true"
    quoted = ",".join(f'"{r}"' for r in regions)
    return f"    include_only = [{quoted}]"


def _build_aws_provider_block(profile: str) -> str:
    if profile:
        return f'provider "aws" {{\n  profile = "{profile}"\n}}'
    return 'provider "aws" {}'


def cmd_gen(args: argparse.Namespace) -> None:
    if not args.account:
        _die("--account is required")
    _validate_account(args.account)
    if not args.trusted_account:
        _die("--trusted-account is required (site table in SKILL.md)")
    _validate_account(args.trusted_account, "--trusted-account")
    _validate_role_name(args.role_name)
    if not re.fullmatch(r"[a-z0-9.-]+", args.site):
        _die(f"--site {args.site!r} is not a Datadog site name")

    if args.aws_profile is not None:
        if not args.aws_profile or '"' in args.aws_profile:
            _die("--aws-profile must be a non-empty name without double quotes")

    regions = _parse_regions(args.regions or "")
    regions_block = _build_regions_block(regions)
    aws_provider_block = _build_aws_provider_block(args.aws_profile or "")

    content = (
        _TEMPLATE
        .replace("@@SITE@@", args.site)
        .replace("@@TRUSTED@@", args.trusted_account)
        .replace("@@AWS_PROVIDER_BLOCK@@", aws_provider_block)
        .replace("@@ROLE_NAME@@", args.role_name)
        .replace("@@ACCOUNT@@", args.account)
        .replace("@@REGIONS_BLOCK@@", regions_block)
    )

    # Sanity: no placeholder may survive
    if re.search(r"<[A-Z_]+>|<DD_SITE>|<AWS_ACCOUNT_ID>|<DATADOG_TRUSTED_ACCOUNT_ID>", content):
        _die("internal error: a placeholder survived generation", 3)
    if "@@" in content:
        _die("internal error: an @@-marker survived generation", 3)

    out_dir = pathlib.Path(args.dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "main.tf"

    if out_path.exists() and not args.force:
        _die(f"{out_path} already exists — pass --force to overwrite", 2)

    out_path.write_text(content)

    regions_label = ",".join(regions) if regions else "all"
    print(
        f"✓ wrote {out_path} "
        f"(site {args.site} · account {args.account} · trusted {args.trusted_account} · regions: {regions_label})"
    )
    chdir = shlex.quote(f"-chdir={out_dir}")
    print(f"next: terraform {chdir} init && terraform {chdir} plan -out=tfplan   # then apply only after review")


