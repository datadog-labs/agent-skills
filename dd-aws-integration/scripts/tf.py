def main() -> None:
    parser = argparse.ArgumentParser(prog="tf.py", description=__doc__)
    sub = parser.add_subparsers(dest="cmd", required=True)

    # --- gen ---
    gen_p = sub.add_parser("gen", help="Emit main.tf for the Datadog AWS integration")
    gen_p.add_argument("--site", default=os.environ.get("DD_SITE") or "datadoghq.com",
                       help="Datadog site (default: $DD_SITE, else datadoghq.com)")
    gen_p.add_argument("--account", required=True)
    gen_p.add_argument("--trusted-account", required=True, dest="trusted_account")
    gen_p.add_argument("--dir", default="./dd-aws-integration")
    gen_p.add_argument("--regions", default="")
    gen_p.add_argument("--role-name", default=DEFAULT_ROLE_NAME, dest="role_name")
    gen_p.add_argument("--aws-profile", default=None, dest="aws_profile")
    gen_p.add_argument("--force", action="store_true")

    # --- precheck ---
    pre_p = sub.add_parser("precheck", help="Check state before first apply")
    pre_p.add_argument("--account", required=True)
    pre_p.add_argument(
        "--dir", default=None,
        help="Terraform project to inspect (default: ./dd-aws-integration if it has .tf files, else the current directory if it does)",
    )
    pre_p.add_argument("--role-name", default=None, dest="role_name",
                       help=f"IAM role name to verify (default {DEFAULT_ROLE_NAME}); default-name "
                            "collisions are auto-resolved with a MMDD date suffix")
    pre_p.add_argument("--aws-profile", default=None, dest="aws_profile")

    # --- fix ---
    fix_p = sub.add_parser("fix", help="Recover from an apply 409 on the integration's policy names")
    fix_p.add_argument("--dir", default="./dd-aws-integration")
    fix_p.add_argument("--aws-profile", default=None, dest="aws_profile")

    args = parser.parse_args()
    if args.cmd == "gen":
        cmd_gen(args)
    elif args.cmd == "precheck":
        cmd_precheck(args)
    elif args.cmd == "fix":
        cmd_fix(args)


if __name__ == "__main__":
    main()
